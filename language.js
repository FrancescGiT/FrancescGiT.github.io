function localized(original, lang) {
  const trimmed = original.trim();
  if (!trimmed) return original;
  let next = trimmed;
  if (lang === "en") {
    if (Object.hasOwn(English, trimmed)) next = English[trimmed];
    const category = trimmed.match(/^(\d{2}) \/ (IA|PRODUCTO)$/);
    if (category) next = category[1] + " / " + (category[2] === "IA" ? "AI" : "PRODUCT");
  } else if (Object.hasOwn(Spanish, trimmed)) {
    next = Spanish[trimmed];
  }
  if (trimmed === next) return original;
  return original.replace(trimmed, next);
}

function translatePage(lang) {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    const parent = node.parentElement;
    if (!parent || parent.closest("script, style, noscript, .language-menu")) continue;
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    const original = originalText.get(node);
    node.nodeValue = localized(original, lang);
  }
  document.documentElement.lang = lang;
  document.documentElement.dataset.language = lang;
  document.title = lang === "en"
    ? "Francesc Benach Garcia | Engineering and Digital Systems"
    : "Francesc Benach Garcia | Ingeniería y sistemas digitales";
  const description = document.querySelector('meta[name="description"]');
  if (description) description.content = lang === "en"
    ? "Francesc Benach Garcia. Electronic engineering, firmware, project management and digital transformation."
    : "Francesc Benach Garcia. Ingeniería electrónica, firmware, dirección de proyectos y transformación digital.";
  const heroResume = document.querySelector(".hero .btn.secondary");
  if (heroResume) heroResume.href = lang === "en" ? "./files/Francesc_Benach_CV_EN.pdf" : "./files/Francesc_Benach_CV_ES.pdf";
  const ogTitle = document.querySelector('meta[property="og:title"]');
  if (ogTitle) ogTitle.content = lang === "en" ? "Francesc Benach Garcia | Engineering and digital systems" : "Francesc Benach Garcia | Ingeniería y sistemas digitales";
  const og = document.querySelector('meta[property="og:description"]');
  if (og) og.content = lang === "en"
    ? "Electronic engineering, embedded systems, product development and digital transformation."
    : "Ingeniería electrónica, sistemas embebidos, producto y transformación digital.";
  const nav = document.getElementById("navigation");
  nav.setAttribute("aria-label", lang === "en" ? "Main navigation" : "Navegación principal");
  const mobile = document.getElementById("mobileMenu");
  mobile.setAttribute("aria-label", lang === "en" ? "Open navigation menu" : "Abrir menú");
  const filters = document.querySelector(".filters");
  filters.setAttribute("aria-label", lang === "en" ? "Filter projects" : "Filtrar proyectos");
  trigger.setAttribute("aria-label", lang === "en" ? "Select language" : "Seleccionar idioma");
  menu.setAttribute("aria-label", lang === "en" ? "Language" : "Idioma");
  languageFlag.textContent = lang === "en" ? "🇺🇸" : "🇪🇸";
  languageCode.textContent = lang.toUpperCase();
  options.forEach(option => option.setAttribute("aria-checked", String(option.dataset.lang === lang)));
}

function closeMenu(restoreFocus = false) {
  menu.hidden = true;
  trigger.setAttribute("aria-expanded", "false");
  if (restoreFocus) trigger.focus();
}
function openMenu() {
  menu.hidden = false;
  trigger.setAttribute("aria-expanded", "true");
  const selected = menu.querySelector('[aria-checked="true"]');
  (selected || options[0]).focus();
}
function selectLanguage(lang) {
  if (lang !== "es" && lang !== "en") return;
  language = lang;
  translatePage(lang);
  try { window.localStorage.setItem(memoryKey, lang); } catch {}
  closeMenu(true);
}

let preferred;
try { preferred = window.localStorage.getItem(memoryKey); } catch {}
const browserLanguage = (navigator.languages?.[0] || navigator.language || "es").toLowerCase();
language = preferred === "es" || preferred === "en"
  ? preferred
  : browserLanguage.startsWith("en") ? "en" : "es";
translatePage(language);

trigger.addEventListener("click", () => {
  if (menu.hidden) openMenu();
  else closeMenu(true);
});
options.forEach(option => option.addEventListener("click", () => selectLanguage(option.dataset.lang)));
picker.addEventListener("keydown", event => {
  if (event.key === "Escape" && !menu.hidden) {
    event.preventDefault();
    closeMenu(true);
  }
  if ((event.key === "ArrowDown" || event.key === "ArrowUp") && menu.hidden) {
    event.preventDefault();
    openMenu();
  } else if ((event.key === "ArrowDown" || event.key === "ArrowUp") && !menu.hidden) {
    event.preventDefault();
    const index = options.indexOf(document.activeElement);
    const delta = event.key === "ArrowDown" ? 1 : -1;
    options[(index + delta + options.length) % options.length].focus();
  }
});
document.addEventListener("pointerdown", event => {
  if (!picker.contains(event.target)) closeMenu();
});
document.addEventListener("focusin", event => {
  if (!picker.contains(event.target)) closeMenu();
});

